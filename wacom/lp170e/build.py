# Build the LP-170E position-only test image from stock S640-251022.bin:  python3 build.py out.bin
# Needs arm-none-eabi-gcc (nix-shell -p gcc-arm-embedded python3). See trk.c for what it does.
import hashlib, os, re, subprocess, sys

STOCK = "S640-251022.bin"   # put the stock image in this folder
STOCK_SHA = "150fbc8b9cf356224245865c76ebab194083d72d32225921e6af55e83a287b45"
BASE, END = 0x0800C464, 0x0800D000   # free flash after the image, below the settings pages (hot code runs from SRAM, see trk.c)

def bl(pc, target):  # Thumb-2 BL, as bytes
    off = target - (pc + 4)
    s = (off >> 24) & 1; i1 = (off >> 23) & 1; i2 = (off >> 22) & 1
    j1 = (~(i1 ^ s)) & 1; j2 = (~(i2 ^ s)) & 1
    hw1 = 0xF000 | s << 10 | (off >> 12) & 0x3FF
    hw2 = 0xD000 | j1 << 13 | j2 << 11 | (off >> 1) & 0x7FF
    return hw1.to_bytes(2, "little") + hw2.to_bytes(2, "little")

def b_n(pc, target):  # Thumb B (16-bit)
    off = target - (pc + 4)
    assert -2048 <= off < 2048
    return (0xE000 | (off >> 1) & 0x7FF).to_bytes(2, "little")

assert bl(0x08006822, 0x08002834).hex() == "fcf707f8" and bl(0x08006822, 0x0800C464).hex() == "05f01ffe"
assert b_n(0x08006702, 0x08006694).hex() == "c7e7"

def run(cmd): return subprocess.run(cmd, shell=True, check=True, capture_output=True, text=True).stdout

run("arm-none-eabi-gcc -mcpu=cortex-m3 -mthumb -nostdlib -Ttext=0x20001A00 vburst.s -o vburst.elf && arm-none-eabi-objcopy -O binary vburst.elf vburst.bin")
vb = open("vburst.bin", "rb").read()
sled_end = int(re.search(r"([0-9a-f]+) . sled_end", run("arm-none-eabi-nm vburst.elf")).group(1), 16)
with open("vb.h", "w") as h:
    h.write("/* generated by build.py from vburst.s (linked at 0x20001A00) */\n")
    h.write(f"#define VB_SLED_END 0x{sled_end:08X}u\nstatic const uint8_t vb[{len(vb)}] = {{\n")
    for i in range(0, len(vb), 16): h.write("  " + ", ".join(f"0x{x:02x}" for x in vb[i:i + 16]) + ",\n")
    h.write("};\n")
run("arm-none-eabi-gcc -mcpu=cortex-m3 -mthumb -Os -ffreestanding -nostdlib -fno-builtin "
    "-fno-tree-loop-distribute-patterns -Wall -Werror " + os.environ.get("CFLAGS", "") + " -T link.ld trk.c -o trk.elf")
assert run("arm-none-eabi-nm -u trk.elf").strip() == "", "undefined symbols (library calls?)"
ram = [m.group(1) for m in re.finditer(r"\d+\s+(\.(?:data|bss)\S*)\s+([0-9a-f]+)", run("arm-none-eabi-objdump -h trk.elf")) if int(m.group(2), 16)]
assert not ram, f"RAM sections {ram}: statics would land in flash; keep state in the fixed RAM block"
syms = {m.group(2): int(m.group(1), 16) for m in re.finditer(r"([0-9a-f]+) T (\w+)", run("arm-none-eabi-nm trk.elf"))}
boot = re.search(r"\.boot\s+[0-9a-f]+\s+([0-9a-f]+)", run("arm-none-eabi-objdump -h trk.elf"))
assert boot and int(boot.group(1), 16) == BASE, "blob must start at BASE (v9: an 8-aligned .boot at 0xC468 shifted everything by 4 -> reset loop)"
run("arm-none-eabi-objcopy -O binary -j .boot -j .text -j .dbg trk.elf trk.bin")
blob = open("trk.bin", "rb").read()
assert BASE + len(blob) <= END, f"blob too big: {len(blob)}"

b = bytearray(open(STOCK, "rb").read())
assert hashlib.sha256(b).hexdigest() == STOCK_SHA, "not the stock S640-251022.bin"
assert len(b) == BASE - 0x08000000
patches = [  # (address, original bytes, new bytes)
    (0x08006678, "fdf7def9", bl(0x08006678, syms["trk_init"])),          # bl 0x08003A38 -> bl trk_init
    (0x08006794, "e07ac0b10128", bl(0x08006794, syms["trk_step_flash"]) + b_n(0x08006798, 0x08006694)),  # dispatch -> bl trk_step_flash (-> SRAM trk_step); b loop top
]
for a, old, new in patches:
    o = a - 0x08000000
    assert b[o:o + len(new)].hex() == old, hex(a)
    b[o:o + len(new)] = new
b += blob
open(sys.argv[1], "wb").write(b)
print(f"{sys.argv[1]}: {len(b)} bytes (blob {len(blob)} at 0x{BASE:08X}), trk_init 0x{syms['trk_init']:08X}, "
      f"trk_step 0x{syms['trk_step']:08X}, sled_end 0x{sled_end:08X}, sha256 {hashlib.sha256(b).hexdigest()}")
